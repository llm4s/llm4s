#!/usr/bin/env python3
"""Generates the two copies of `WindowsBestFit.scala` (#1766).

On Windows a program that reads its command line in an ANSI code page (`main` rather than `wmain`) gets each
argument converted from UTF-16 with "best fit": a character the code page cannot hold may become a similar ASCII
one, so a fullwidth reverse solidus (U+FF3C) arrives as `\\`, a yen sign (U+00A5) as `\\` on code page 932, a
soft hyphen (U+00AD) as `-`. ShellTool (`modules/agent-tools`) and the workspace runner's command policy
(`modules/workspace/workspaceRunner`) refuse such characters on Windows, from the table this script writes.

The table is every non-ASCII character that the `WCTABLE` (Unicode to code page) section of Microsoft's best-fit
file for one of the code pages below maps to a single ASCII byte, with the ASCII characters it maps to. The files
are Microsoft's, published by the Unicode Consortium:

    https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WindowsBestFit/bestfit<cp>.txt

The two modules share no dependency that could hold one copy (the runner depends on `workspaceShared` only), so
both are generated from this one template. Usage:

    scripts/generate-windows-best-fit.py            # download the files and write both copies
    scripts/generate-windows-best-fit.py --check    # fail when a copy differs from what would be written
    scripts/generate-windows-best-fit.py --dir DIR  # read bestfit<cp>.txt from DIR instead of downloading

The output is already formatted as scalafmt leaves it.
"""

import argparse
import os
import re
import sys
import urllib.request

CODE_PAGES = [874, 932, 936, 949, 950, 1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258]
BASE_URL = "https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WindowsBestFit/"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TARGETS = [
    (
        "modules/agent-tools/src/main/scala/org/llm4s/toolapi/builtin/shell/WindowsBestFit.scala",
        "org.llm4s.toolapi.builtin.shell",
        "builtin",
    ),
    (
        "modules/workspace/workspaceRunner/src/main/scala/org/llm4s/runner/WindowsBestFit.scala",
        "org.llm4s.runner",
        "runner",
    ),
]

SECTIONS = {"CODEPAGE", "CPINFO", "MBTABLE", "DBCSRANGE", "DBCSTABLE", "WCTABLE", "ENDCODEPAGE"}


def read_code_page(cp, directory):
    if directory:
        with open(os.path.join(directory, f"bestfit{cp}.txt"), "rb") as f:
            return f.read().decode("latin-1")
    with urllib.request.urlopen(f"{BASE_URL}bestfit{cp}.txt", timeout=60) as response:
        return response.read().decode("latin-1")


def best_fits(directory):
    """{code point: set of ASCII bytes} over every code page."""
    table = {}
    for cp in CODE_PAGES:
        section = None
        for line in read_code_page(cp, directory).splitlines():
            line = line.strip()
            if not line:
                continue
            word = line.split()[0].upper()
            if word in SECTIONS:
                section = word
                continue
            if section != "WCTABLE":
                continue
            m = re.match(r"0x([0-9a-fA-F]+)\s+0x([0-9a-fA-F]+)", line)
            if m:
                unicode, byte = int(m.group(1), 16), int(m.group(2), 16)
                if unicode >= 0x80 and byte < 0x80:
                    table.setdefault(unicode, set()).add(byte)
    return table


ESCAPES = {0x22: '\\"', 0x5C: "\\\\", 0x08: "\\b", 0x09: "\\t", 0x0A: "\\n", 0x0C: "\\f", 0x0D: "\\r"}


def literal(c):
    """`c` inside a Scala string literal. A key (non-ASCII) is a `\\u` escape; an ASCII target is written as itself or
    with a backslash escape, since scalafmt's parser reads `\\u0022` as a quote that ends the literal."""
    if c >= 0x80:
        return f"\\u{c:04X}"
    if c in ESCAPES:
        return ESCAPES[c]
    if 0x20 <= c < 0x7F:
        return chr(c)
    return f"\\u{c:04X}"


def encoded_lines(table):
    entries = ["".join(literal(c) for c in [u] + sorted(table[u])) for u in sorted(table)]
    lines, current = [], ""
    for entry in entries:
        # 4 spaces of indent, the quotes and a trailing comma within scalafmt's 120 columns
        if len(current) + len(entry) > 120 - 4 - 3:
            lines.append(current)
            current = ""
        current += entry
    lines.append(current)
    return ",\n".join(f'    "{line}"' for line in lines)


TEMPLATE = '''// GENERATED by scripts/generate-windows-best-fit.py from Microsoft's best-fit tables; do not edit by hand.
// The same file is generated into modules/agent-tools and modules/workspace/workspaceRunner.
package {package}

import java.nio.charset.{{ Charset, StandardCharsets }}
import java.util.Locale
import scala.util.Try

/**
 * Characters a Windows program may receive as different ASCII characters ("best fit", #1766).
 *
 * A Windows program that reads its command line in an ANSI code page (`main` rather than `wmain`, or any
 * conversion through `WideCharToMultiByte` without `WC_NO_BEST_FIT_CHARS`) gets each argument converted from UTF-16
 * with best fit: a character the code page cannot hold may become a similar ASCII one. A fullwidth reverse solidus
 * (U+FF3C) arrives as `\\`, a fullwidth solidus (U+FF0F) as `/`, a yen (U+00A5) or won (U+20A9) sign as `\\` on the
 * Japanese and Korean code pages, a soft hyphen (U+00AD) as `-`, an ideographic space (U+3000) as a space that
 * splits the argument in two. An argument such as `..／..／secret` is one plain name to a check that reads
 * UTF-16, and `../../secret` to the program ("WorstFit", Orange Tsai, 2025). A character none of the code page's
 * mappings covers becomes the default character, `?`.
 *
 * So on Windows an argument, the working directory and an environment value are refused when they hold:
 *
 *  - a character that a common ANSI code page (874, 932, 936, 949, 950, 1250 to 1258) best-fits to an ASCII
 *    character that is not a letter or digit: a separator, a quote, a colon, a wildcard, a space, a control
 *    character, an option dash, a dot, any punctuation;
 *  - in an option-like value (starting with `-` or `/`), a character best-fitted to any ASCII character, since a
 *    letter there may be an option the checks did not see (`-ö` is `-o` on code page 1251);
 *  - on a Windows host, a character the host's own ANSI code page cannot hold exactly ([[hostAnsiCodePage]]): a
 *    program that reads its arguments in it would receive a best fit or `?`, whatever table it comes from.
 *
 * Accented letters (`é`, `ü`) and other characters that best-fit only to a letter or digit stay allowed in an
 * operand when the host's code page holds them, so `résumé.txt` can still be named on a Western European host.
 *
 * The table is every non-ASCII character that the `WCTABLE` section of Microsoft's best-fit file for one of those
 * code pages maps to a single ASCII byte, with the ASCII characters it maps to
 * (https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WindowsBestFit/); `scripts/generate-windows-best-fit.py`
 * writes it, and `--check` compares both copies with what it would write.
 */
private[{visibility}] object WindowsBestFit {{

  /** The ASCII characters some common ANSI code page best-fits `c` to; empty when none does. */
  def substitutes(c: Char): String = Substitutes.getOrElse(c, "")

  /** Whether a program may read `value` as an option or a switch (`-x`, `/x`), where a letter matters too. */
  def isOptionLike(value: String): Boolean = value.startsWith("-") || value.startsWith("/")

  /**
   * The ANSI code page of the Windows host this runs on (the JDK's `sun.jnu.encoding`), or `None` on another host
   * and when the code page is UTF-8, which converts every character exactly.
   */
  val hostAnsiCodePage: Option[Charset] =
    if (!System.getProperty("os.name", "").toLowerCase(Locale.ROOT).startsWith("windows")) None
    else
      Option(System.getProperty("sun.jnu.encoding"))
        .orElse(Option(System.getProperty("native.encoding")))
        .flatMap(name => Try(Charset.forName(name)).toOption)
        .filter(_ != StandardCharsets.UTF_8)

  /**
   * Why `value` may not be given to a program on Windows - its first character that the program may receive as
   * another one, and what it may become - or `None`.
   *
   * @param optionLike   whether the program may read `value` as an option or switch ([[isOptionLike]])
   * @param ansiCodePage the host's ANSI code page ([[hostAnsiCodePage]]), whose characters must convert exactly
   */
  def refusal(value: String, optionLike: Boolean, ansiCodePage: Option[Charset]): Option[String] =
    codePoints(value).filter(_ >= 0x80).flatMap(problem(_, optionLike, ansiCodePage)).nextOption()

  private def problem(cp: Int, optionLike: Boolean, ansiCodePage: Option[Charset]): Option[String] = {{
    val fits = if (Character.isBmpCodePoint(cp)) substitutes(cp.toChar) else ""
    if (fits.exists(c => !c.isLetterOrDigit) || (optionLike && fits.nonEmpty))
      Some(
        s"${{describe(cp)}}, which a program reading its arguments in a Windows ANSI code page may receive as " +
          fits.map(show).mkString(" or ")
      )
    else
      ansiCodePage
        .filterNot(roundTrips(cp, _))
        .map(cs =>
          s"${{describe(cp)}}, which this host's ANSI code page (${{cs.name}}) cannot hold, so a program reading its " +
            "arguments in it would receive another character"
        )
  }}

  private def roundTrips(cp: Int, cs: Charset): Boolean = {{
    val s = new String(Character.toChars(cp))
    Try(new String(s.getBytes(cs), cs) == s).getOrElse(false)
  }}

  private def codePoints(value: String): Iterator[Int] =
    Iterator.unfold(0)(at =>
      if (at >= value.length) None
      else {{
        val cp = value.codePointAt(at)
        Some((cp, at + Character.charCount(cp)))
      }}
    )

  private def describe(cp: Int): String = f"'${{new String(Character.toChars(cp))}}' (U+$cp%04X)"

  private def show(c: Char): String = if (c < ' ' || c == '\\u007f') f"U+${{c.toInt}}%04X" else s"'$c'"

  /** `Encoded` read back: each non-ASCII character with the ASCII characters it is best-fitted to. */
  private lazy val Substitutes: Map[Char, String] =
    Encoded
      .foldLeft(List.empty[(Char, String)]) {{ (entries, c) =>
        if (c >= '\\u0080') (c, "") :: entries
        else
          entries match {{
            case (key, fits) :: rest => (key, fits + c) :: rest
            case Nil                 => Nil
          }}
      }}
      .toMap

  /**
   * Each entry is a non-ASCII character followed by the ASCII characters some code page best-fits it to
   * ({count} characters).
   */
  private val Encoded: String = Seq(
{lines}
  ).mkString
}}
'''


def render(table, package, visibility):
    return TEMPLATE.format(package=package, visibility=visibility, count=len(table), lines=encoded_lines(table))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a copy is not what would be written")
    parser.add_argument("--dir", help="read bestfit<cp>.txt from this directory instead of downloading")
    args = parser.parse_args()
    table = best_fits(args.dir)
    stale = []
    for path, package, visibility in TARGETS:
        full = os.path.join(ROOT, path)
        content = render(table, package, visibility)
        if args.check:
            current = open(full, encoding="utf-8").read() if os.path.exists(full) else None
            if current != content:
                stale.append(path)
        else:
            with open(full, "w", encoding="utf-8") as f:
                f.write(content)
            print(f"wrote {path} ({len(table)} characters)")
    if stale:
        print("out of date (run scripts/generate-windows-best-fit.py): " + ", ".join(stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
