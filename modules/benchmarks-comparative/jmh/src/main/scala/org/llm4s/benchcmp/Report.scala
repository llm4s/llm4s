package org.llm4s.benchcmp

import java.nio.charset.StandardCharsets
import java.nio.file.{ Files, Path }

/**
 * Writes the results page's tables from the run's JSON: `jmh.json` (JMH's `-rf json`) and `coldstart.json` (the
 * build's `comparativeColdStart` task), both in the directory given as the only argument, into `results.md` there.
 * Nothing in the tables is typed by hand.
 */
object Report:

  private val Libs = Seq("llm4s", "langchain4j", "spring-ai")

  final case class Row(benchmark: String, library: String, chunks: Option[String], metric: ujson.Value)

  def main(args: Array[String]): Unit =
    val dir  = Path.of(args.headOption.getOrElse("target/comparative"))
    val jmh  = ujson.read(Files.readString(dir.resolve("jmh.json")))
    val cold = ujson.read(Files.readString(dir.resolve("coldstart.json")))
    val out  = dir.resolve("results.md")
    Files.writeString(out, render(jmh, cold), StandardCharsets.UTF_8)
    println(s"Wrote $out")

  def render(jmh: ujson.Value, cold: ujson.Value): String =
    val rows = jmh.arr.toSeq.map { r =>
      val params = r.obj.get("params").map(_.obj).getOrElse(collection.mutable.LinkedHashMap.empty[String, ujson.Value])
      Row(
        r("benchmark").str.split('.').takeRight(2).mkString("."),
        params.get("library").map(_.str).getOrElse("?"),
        params.get("chunks").map(_.str),
        r
      )
    }
    def find(bench: String, lib: String, chunks: Option[String] = None) =
      rows.find(r => r.benchmark.endsWith(bench) && r.library == lib && (chunks.isEmpty || r.chunks == chunks))
    def pct(r: Row, p: String): Option[Double] =
      r.metric("primaryMetric").obj.get("scorePercentiles").flatMap(_.obj.get(p)).map(_.num)
    def mean(r: Row): Double = r.metric("primaryMetric")("score").num
    def unit(r: Row): String = r.metric("primaryMetric")("scoreUnit").str.replace("/op", "")
    def alloc(r: Row): Option[Double] =
      r.metric.obj
        .get("secondaryMetrics")
        .flatMap(m => m.obj.get("gc.alloc.rate.norm").orElse(m.obj.get("·gc.alloc.rate.norm")))
        .map(_("score").num)
    def f(d: Double): String  = if d >= 100 then f"$d%.0f" else if d >= 10 then f"$d%.1f" else f"$d%.2f"
    def kb(d: Double): String = f(d / 1024)

    val sb                         = new StringBuilder
    def line(s: String = ""): Unit = sb.append(s).append('\n')

    val first = jmh.arr.headOption
    line("<!-- Generated by org.llm4s.benchcmp.Report from jmh.json and coldstart.json. Do not edit by hand. -->")
    line()
    line("| Run | |")
    line("|---|---|")
    first.foreach { r =>
      line(
        s"| JDK | ${r("vmName").str} ${r("vmVersion").str} (`${r.obj.get("jdkVersion").map(_.str).getOrElse("")}`) |"
      )
      line(s"| JVM flags | `${r("jvmArgs").arr.map(_.str).mkString(" ")}` |")
      line(s"| JMH | ${r("jmhVersion").str}, ${r("forks").num.toInt} fork(s), ${r("warmupIterations").num.toInt} x ${r(
          "warmupTime"
        ).str} warm-up, ${r("measurementIterations").num.toInt} x ${r("measurementTime").str} measurement |")
    }
    val cpu = cold.obj.get("cpu").map(_.str).filter(_.nonEmpty).map(c => s"$c, ").getOrElse("")
    line(s"| Machine | ${cold("os").str}, $cpu${cold("cpus").num.toInt} CPUs |")
    line(s"| Versions | ${Libs.map(l => s"$l ${cold("versions")(l).str}").mkString(", ")} |")
    line()

    line(
      "**Latency per operation** (JMH sample time; lower is better; alloc is `-prof gc` bytes allocated per operation, in KB)"
    )
    line()
    line(s"| Scenario | ${Libs.map(l => s"$l p50 | $l p99 | $l alloc").mkString(" | ")} |")
    line(s"|---|${Libs.map(_ => "---:|---:|---:").mkString("|")}|")
    val scenarios = Seq(
      ("Chat completion", "chat", None),
      ("Stream, 1 chunk", "stream", Some("1")),
      ("Stream, 500 chunks", "stream", Some("500")),
      ("Tool agent, 3 rounds", "toolAgent", None),
      ("200 concurrent chats", "concurrent200", None)
    )
    scenarios.foreach { case (label, bench, chunks) =>
      val cells = Libs.map { l =>
        find(bench, l, chunks) match
          case Some(r) =>
            val u = unit(r)
            Seq(
              pct(r, "50.0").map(d => s"${f(d)} $u").getOrElse("-"),
              pct(r, "99.0").map(d => s"${f(d)} $u").getOrElse("-"),
              alloc(r).map(kb).getOrElse("-")
            ).mkString(" | ")
          case None => "- | - | -"
      }
      if cells.exists(_ != "- | - | -") then line(s"| $label | ${cells.mkString(" | ")} |")
    }
    line()
    line(
      "The 200 concurrent chats run on virtual threads, except Spring AI's, which run on a pool of 200 platform threads:"
    )
    line("its OkHttp client deadlocked on virtual threads on JDK 21 (`SpringAiLibrary.virtualThreads`).")
    line()

    line("**Derived** (from the means above)")
    line()
    line(s"| Measure | ${Libs.mkString(" | ")} |")
    line(s"|---|${Libs.map(_ => "---:").mkString("|")}|")
    def derived(label: String)(g: String => Option[String]): Unit =
      val cells = Libs.map(l => g(l).getOrElse("-"))
      if cells.exists(_ != "-") then line(s"| $label | ${cells.mkString(" | ")} |")
    def toMicros(r: Row): Double = unit(r) match
      case "ms" => mean(r) * 1000
      case "ns" => mean(r) / 1000
      case "s"  => mean(r) * 1e6
      case _    => mean(r)
    derived("Per streamed chunk, (500 - 1) / 499") { l =>
      for
        a <- find("stream", l, Some("500"))
        b <- find("stream", l, Some("1"))
      yield s"${f((toMicros(a) - toMicros(b)) / 499)} us"
    }
    derived("Per tool round trip, run / 4 HTTP calls") { l =>
      find("toolAgent", l).map(r => s"${f(toMicros(r) / 4)} us")
    }
    derived("200 concurrent chats, throughput") { l =>
      find("concurrent200", l).map(r => s"${f(200 / (toMicros(r) / 1e6))} calls/s")
    }
    line()

    line(
      s"**Cold start and footprint** (median of ${cold("runs").num.toInt} fresh JVMs; process launch to first reply printed)"
    )
    line()
    line("| Library | Cold start p50 | min | max | Jars | Jar MB |")
    line("|---|---:|---:|---:|---:|---:|")
    Libs.foreach { l =>
      cold("libraries").obj.get(l).foreach { c =>
        val ms  = c("coldStartMs").arr.map(_.num).sorted
        val p50 = ms(ms.size / 2)
        line(
          s"| $l | ${f(p50)} ms | ${f(ms.head)} ms | ${f(ms.last)} ms | ${c("jars").num.toInt} | ${f(c("jarBytes").num / 1e6)} |"
        )
      }
    }
    sb.toString
