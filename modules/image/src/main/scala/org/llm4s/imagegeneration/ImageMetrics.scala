package org.llm4s.imagegeneration

import org.llm4s.annotation.Experimental
import org.llm4s.metrics.{ Metric, MetricsCollector, Outcome }
import org.llm4s.reliability.ReliabilityMetrics

import scala.concurrent.duration._

/**
 * The metrics [[InstrumentedImageGenerationClient]] records, declared as [[org.llm4s.metrics.Metric Metric]]s and
 * recorded through [[org.llm4s.metrics.MetricsCollector.increment MetricsCollector.increment]] and
 * [[org.llm4s.metrics.MetricsCollector.observe MetricsCollector.observe]], so every backend that exports generic
 * metrics exports them, and core names nothing about image generation (#2801). They were two methods of
 * `MetricsCollector`, `observeImageGeneration` and `recordImageGenerationCost`.
 *
 * The exported series are the ones those methods produced. A Prometheus backend exposes them as
 * `llm4s_image_generations_total`, `llm4s_images_generated_total`, `llm4s_image_generation_duration_seconds`,
 * `llm4s_image_generation_cost_usd_total` and `llm4s_image_generation_errors_total`; a Micrometer one under the
 * names below. `ImageMetricsSeriesSpec` pins every name, type, label and bucket.
 *
 * A failed operation is also added to [[org.llm4s.metrics.MetricsCollector.Errors MetricsCollector.Errors]]
 * (`llm4s_errors_total`), the count of failed operations a backend keeps for every kind of request.
 */
@Experimental
object ImageMetrics {

  /**
   * Image generation operations, successful or not. Labels: `provider`, `model`, `operation` (`generate` or
   * `edit`), `status` (`success`, or `error_` and the error type: see [[statusLabel]]).
   */
  val Generations: Metric.Counter =
    Metric.counter(
      "llm4s.image.generations",
      "Total number of image generation operations",
      "provider",
      "model",
      "operation",
      "status"
    )

  /** Images generated by successful operations. Labels: `provider`, `model`. */
  val ImagesGenerated: Metric.Counter =
    Metric.counter("llm4s.images.generated", "Total number of images generated", "provider", "model")

  /** How long each operation took, successful or not. Labels: `provider`, `model`, `operation`. */
  val Duration: Metric.Timer =
    Metric.timer(
      "llm4s.image.generation.duration",
      "Image generation duration in seconds",
      Seq(1.second, 2.seconds, 5.seconds, 10.seconds, 30.seconds, 60.seconds, 120.seconds, 300.seconds),
      "provider",
      "model",
      "operation"
    )

  /** Estimated cost of the images generated, in USD. Labels: `provider`, `model`. */
  val CostUsd: Metric.Counter =
    Metric.counter(
      "llm4s.image.generation.cost.usd",
      "Total estimated image generation cost in USD",
      "provider",
      "model"
    )

  /**
   * Failed image generation operations. Labels: `provider`, `model`, `operation`, `error_type` (an
   * [[org.llm4s.metrics.ErrorKind ErrorKind]], in snake case).
   */
  val Errors: Metric.Counter =
    Metric.counter(
      "llm4s.image.generation.errors",
      "Total number of image generation errors",
      "provider",
      "model",
      "operation",
      "error_type"
    )

  /** The `status` label of [[Generations]] for `outcome`: `success`, or `error_rate_limit` and the like. */
  def statusLabel(outcome: Outcome): String = outcome match {
    case Outcome.Success     => "success"
    case Outcome.Error(kind) => s"error_${ReliabilityMetrics.errorTypeLabel(kind)}"
  }

  /** One operation: its count and duration, the images of a success, the two error counts of a failure. */
  private[imagegeneration] def observed(
    collector: MetricsCollector,
    provider: String,
    model: String,
    operation: String,
    outcome: Outcome,
    duration: FiniteDuration,
    imageCount: Int
  ): Unit = {
    collector.increment(Generations, Seq(provider, model, operation, statusLabel(outcome)))
    collector.observe(Duration, Seq(provider, model, operation), duration)
    outcome match {
      case Outcome.Success =>
        if (imageCount > 0) collector.increment(ImagesGenerated, Seq(provider, model), imageCount.toDouble)
      case Outcome.Error(kind) =>
        val errorType = ReliabilityMetrics.errorTypeLabel(kind)
        collector.increment(MetricsCollector.Errors, Seq(provider, errorType))
        collector.increment(Errors, Seq(provider, model, operation, errorType))
    }
  }

  /** The estimated cost of one successful operation. */
  private[imagegeneration] def cost(collector: MetricsCollector, provider: String, model: String, usd: Double): Unit =
    collector.increment(CostUsd, Seq(provider, model), usd)
}
